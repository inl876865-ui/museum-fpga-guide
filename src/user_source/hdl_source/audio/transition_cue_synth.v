                    if(envelope_position[21:16]==63) begin envelope_gain<=rom_data;interpolation<=0;state<=MUL_SETUP;end
                    else state<=NEXT_ADDR;
                end
                NEXT_ADDR:begin rom_address<=envelope_address+1'b1;state<=NEXT_WAIT;end
                NEXT_WAIT:state<=NEXT_LATCH;
                NEXT_LATCH:begin interpolation<=1;state<=MUL_SETUP;end
                MUL_SETUP:begin
                    multiplicand<=multiply_magnitude;
                    accumulator<={16'd0,(interpolation ? envelope_position[15:0] : envelope_gain)};
                    multiply_negative<=multiply_left[15];mul_count<=0;state<=MUL_RUN;
                end
                MUL_RUN:begin
                    accumulator<=product_step;
                    if(mul_count==15) state<=MUL_RESULT;else mul_count<=mul_count+1'b1;
                end
                MUL_RESULT:begin
                    if(interpolation) begin envelope_gain<=interpolated_gain[15:0];interpolation<=0;state<=MUL_SETUP;end
                    else begin prepared_data<=output_sample;prepared<=1;state<=WAIT_TICK;end
                end
                default:begin end
            endcase
            // Restart never overwrites a valid transaction held by backpressure.
            if(restarting && (!sample_valid || sample_ready)) restart_cue;
        end
    end
